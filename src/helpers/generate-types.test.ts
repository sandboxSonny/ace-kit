import { describe, expect, it } from "vitest";

import { generateTypes } from "./generate-types";
import type { AceContentTypeSchema } from "../types/content-types";

const pages: AceContentTypeSchema = {
  handle: "pages",
  name: "Pages",
  fields: [
    { handle: "headline", label: "Headline", component_key: "text", config: { required: true } },
    { handle: "summary", label: "Summary", component_key: "textarea", config: {} },
    { handle: "rating", label: "Rating", component_key: "number", config: null },
    { handle: "featured", label: "Featured", component_key: "checkbox", config: {} },
    {
      handle: "tone",
      label: "Tone",
      component_key: "select",
      config: { required: true, options: ["formal", "casual"] },
    },
    { handle: "hero-image", label: "Hero image", component_key: "image", config: {} },
    { handle: "body", label: "Body", component_key: "richtext", config: { required: true } },
    { handle: "mystery", label: "Mystery", component_key: "hologram", config: {} },
  ],
};

describe("generateTypes", () => {
  const output = generateTypes([pages], "@scope/ace-kit", "example.test");

  it("says where it came from and how to update it", () => {
    expect(output).toContain("Generated by ace-kit from example.test");
    expect(output).toContain("ace-kit generate");
  });

  it("adds each content type to AceContentTypes by declaration merging", () => {
    expect(output).toContain('declare module "@scope/ace-kit"');
    expect(output).toContain("interface AceContentTypes");
    expect(output).toContain('"pages": {');
  });

  it("types each kind of field, with required fields not optional", () => {
    expect(output).toContain('"headline": string;');
    expect(output).toContain('"summary"?: string;');
    expect(output).toContain('"rating"?: number;');
    expect(output).toContain('"featured"?: boolean;');
    expect(output).toContain('"tone": "formal" | "casual";');
    expect(output).toContain('"hero-image"?: AceImageData;');
    expect(output).toContain('"body": AceRichTextDocument;');
    expect(output).toContain('"mystery"?: unknown;');
  });

  it("imports only the types it uses", () => {
    expect(output).toContain('import type { AceImageData, AceRichTextDocument } from "@scope/ace-kit";');
    expect(
      generateTypes([{ handle: "notes", name: "Notes", fields: [pages.fields[0]] }], "@scope/ace-kit", "x"),
    ).not.toContain("import type");
  });

  it("copes with a select that has no options, a content type with no fields, and no content types", () => {
    const select = { handle: "s", label: "S", component_key: "select", config: {} };
    expect(generateTypes([{ handle: "a", name: "A", fields: [select] }], "p", "x")).toContain('"s"?: string;');
    expect(generateTypes([{ handle: "a", name: "A", fields: [] }], "p", "x")).toContain('"a": Record<string, never>;');
    expect(generateTypes([], "p", "x")).toContain("interface AceContentTypes");
  });

  it("can't be broken out of by a label that contains a comment ending", () => {
    const text = generateTypes(
      [
        {
          handle: "a",
          name: "*/ evil",
          fields: [{ handle: "b", label: "*/ evil()", component_key: "text", config: {} }],
        },
      ],
      "p",
      "x",
    );
    expect(text).not.toContain("*/ evil");
  });
});
