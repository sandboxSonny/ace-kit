import type { AceContentTypeSchema, AceFieldSchema } from "../types/content-types";

const quote = (text: string) => JSON.stringify(text);

/** The TypeScript type of what a field holds in an entry's values, and which type names it needs from the package. */
function typeOfField(field: AceFieldSchema): { type: string; uses?: "AceImageData" | "AceRichTextDocument" } {
  switch (field.component_key) {
    case "text":
    case "textarea":
      return { type: "string" };
    case "number":
      return { type: "number" };
    case "checkbox":
      return { type: "boolean" };
    case "select": {
      const options = field.config?.options ?? [];
      return { type: options.length > 0 ? options.map(quote).join(" | ") : "string" };
    }
    case "image":
      return { type: "AceImageData", uses: "AceImageData" };
    case "richtext":
      return { type: "AceRichTextDocument", uses: "AceRichTextDocument" };
    default:
      // A kind of field this version of the package doesn't know yet.
      return { type: "unknown" };
  }
}

/**
 * The text of a `.d.ts` file that tells TypeScript the shape of every content type's values, by adding them to
 * `AceContentTypes` (declaration merging). A required field is always there; any other may be missing.
 */
export function generateTypes(contentTypes: AceContentTypeSchema[], packageName: string, source: string): string {
  const used = new Set<string>();
  const blocks = contentTypes.map((contentType) => {
    const lines = contentType.fields.map((field) => {
      const { type, uses } = typeOfField(field);
      if (uses) used.add(uses);
      const optional = field.config?.required === true ? "" : "?";
      return `      /** ${field.label.replace(/\*\//g, "* /")} */\n      ${quote(field.handle)}${optional}: ${type};`;
    });
    const body = lines.length > 0 ? `{\n${lines.join("\n")}\n    }` : "Record<string, never>";
    return `    /** ${contentType.name.replace(/\*\//g, "* /")} */\n    ${quote(contentType.handle)}: ${body};`;
  });

  const imports = used.size > 0 ? `import type { ${[...used].sort().join(", ")} } from ${quote(packageName)};\n\n` : "";
  return `// Generated by ace-kit from ${source}. Do not edit: run \`ace-kit generate\` to update it.
${imports}declare module ${quote(packageName)} {
  interface AceContentTypes {
${blocks.join("\n")}
  }
}

export {};
`;
}
